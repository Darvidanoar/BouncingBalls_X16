#!/usr/bin/env python3
"""
gen_ball.py - generates the pixel data for the Boing ball sprite.

Writes BALL_DATA.INC, a ca65 include file holding a 32x32, 8-bits-per-pixel
image (1024 bytes) that BOING.ASM uploads to VERA as a sprite.

The trick (the same one the original 1984 Amiga demo used):
---------------------------------------------------------------
The ball is never redrawn. Instead, every pixel is given a palette index that
says *which slice of the ball's surface* it belongs to. The assembly program
then spins the ball by recolouring those palette entries every frame
("palette cycling"). Changing 64 palette entries is far cheaper than
redrawing 1024 pixels.

How each pixel's palette index is built:

    index = PAL_BASE + shade * 16 + slice

  slice (0..15): the ball has 16 checker squares around its equator. Each
                 PAIR of squares (one red + one white) is cut into 16 thin
                 vertical slices, so a slice is 1/8 of a square wide.
                 The program colours slices 0-7 red and 8-15 white, then
                 shifts that by one slice per frame, which makes the
                 checkers appear to roll around the ball.
                 Every other band of latitude adds 8 to the slice, which
                 swaps red and white and produces the checkerboard.

  shade (0..3):  simple lighting from the top-left. 0 = brightest.
                 The program keeps a bright and a dark red and white for
                 each shade.

Index 0 means "transparent" for VERA sprites, so pixels outside the
circle are 0.

Run:  python3 gen_ball.py
"""

import math

SIZE = 32            # sprite is SIZE x SIZE pixels (must match BALL_SIZE in BOING.ASM)
PAL_BASE = 32        # first palette entry used by the ball (must match BOING.ASM)
SLICES = 16          # slices per red+white pair (must match BOING.ASM)
SHADES = 4           # lighting levels (must match BOING.ASM)
SQUARES_AROUND = 16  # checker squares around the equator
BANDS = 8            # checker bands from pole to pole
TILT_DEG = -18       # tilt of the spin axis, like the Amiga ball

# Direction the light comes from (x right, y down, z towards the viewer).
LIGHT = (-0.45, -0.55, 0.70)


def normalise(v):
    length = math.sqrt(sum(c * c for c in v))
    return tuple(c / length for c in v)


def pixel_index(px, py):
    """Return the palette index for sprite pixel (px, py), or 0 if outside the ball."""
    radius = SIZE / 2
    # Pixel centre relative to the ball centre, scaled so the ball has radius 1.
    nx = (px + 0.5 - radius) / radius
    ny = (py + 0.5 - radius) / radius
    d2 = nx * nx + ny * ny
    if d2 > 1.0:
        return 0                         # outside the circle: transparent

    nz = math.sqrt(1.0 - d2)             # the visible hemisphere faces the viewer

    # --- lighting (uses the surface normal as seen on screen) ---
    lx, ly, lz = normalise(LIGHT)
    brightness = max(0.0, nx * lx + ny * ly + nz * lz)
    if brightness > 0.80:
        shade = 0
    elif brightness > 0.55:
        shade = 1
    elif brightness > 0.30:
        shade = 2
    else:
        shade = 3

    # --- tilt: rotate the point into the ball's own coordinate system ---
    t = math.radians(TILT_DEG)
    bx = nx * math.cos(t) + ny * math.sin(t)
    by = -nx * math.sin(t) + ny * math.cos(t)
    bz = nz

    # --- longitude: angle around the spin axis, increasing to the right ---
    lon = math.atan2(bx, bz)                       # -pi .. +pi
    fine_steps = SQUARES_AROUND * SLICES // 2      # slices around the whole ball
    lon_step = int((lon + math.pi) / (2 * math.pi) * fine_steps) % fine_steps

    # --- latitude band: 0 at the top pole ... BANDS-1 at the bottom pole ---
    lat = math.asin(max(-1.0, min(1.0, by)))       # -pi/2 .. +pi/2
    band = min(BANDS - 1, int((lat + math.pi / 2) / math.pi * BANDS))

    # Odd bands are shifted by half a pair (8 slices) to form the checkerboard.
    slice_ = (lon_step + (band & 1) * (SLICES // 2)) % SLICES

    return PAL_BASE + shade * SLICES + slice_


def main():
    lines = [
        "; BALL_DATA.INC - generated by gen_ball.py. Do not edit by hand,",
        "; change gen_ball.py and run it again.",
        ";",
        f"; {SIZE}x{SIZE} pixels, 1 byte per pixel (8bpp), {SIZE * SIZE} bytes.",
        f"; Value 0 = transparent, otherwise {PAL_BASE} + shade*{SLICES} + slice.",
        "",
        "ball_pixels:",
    ]
    for py in range(SIZE):
        row = [pixel_index(px, py) for px in range(SIZE)]
        lines.append(f"    ; row {py}")
        # 16 bytes per line keeps lines readable
        for start in range(0, SIZE, 16):
            chunk = ", ".join(f"${v:02X}" for v in row[start:start + 16])
            lines.append(f"    .byte {chunk}")
    with open("BALL_DATA.INC", "w") as f:
        f.write("\n".join(lines) + "\n")
    print("Wrote BALL_DATA.INC")


if __name__ == "__main__":
    main()
